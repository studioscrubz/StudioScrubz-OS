import assert from 'node:assert/strict';
import { execFile, execFileSync } from 'node:child_process';
const database = process.argv[2];
assert.equal(database, 'studioscrubz_inventory_test', 'This test only runs in the disposable native release database');
const args = ['-X', '-qAt', '-v', 'ON_ERROR_STOP=1', '-d', database, '-c'];
const admin = 'f9000000-0000-0000-0000-000000000001';
const location = 'f9000000-0000-0000-0000-000000000002';
const actor = `set role authenticated; select set_config('request.jwt.claim.sub','${admin}',false); `;
const sync = sql => execFileSync('psql', [...args, sql], { encoding: 'utf8' }).trim();
const run = sql => new Promise(resolve => execFile('psql', [...args, actor + sql], { encoding: 'utf8' }, (error, stdout, stderr) => resolve({ ok: !error, stdout, stderr })));
sync(`insert into public.user_profiles(id,role,is_active) values('${admin}','Master Admin',true); insert into public.technician_inventory_locations(id,name,location_type) values('${location}','Concurrency fixture','central');`);
sync(actor + `select public.inventory_move('f9000000-0000-0000-0000-000000000003','trash',10,'purchase','Concurrency setup',null,'${location}');`);
const withdrawals = await Promise.all([4,5].map(i => run(`begin; select public.inventory_move('f9000000-0000-0000-0000-00000000000${i}','trash',8,'consumption','Concurrent consumption','${location}',null); select pg_sleep(0.2); commit;`)));
assert.equal(withdrawals.filter(r => r.ok).length, 1, JSON.stringify(withdrawals));
assert.match(withdrawals.find(r => !r.ok).stderr, /Insufficient source stock/);
assert.equal(sync(`select quantity from public.technician_inventory_stock where location_id='${location}' and item_key='trash'`), '2');
const retry = `select public.inventory_move('f9000000-0000-0000-0000-000000000006','trash',3,'purchase','Concurrent identical retry',null,'${location}');`;
const retries = await Promise.all([run(retry), run(retry)]);
assert.ok(retries.every(r => r.ok), JSON.stringify(retries));
assert.equal(sync(`select quantity from public.technician_inventory_stock where location_id='${location}' and item_key='trash'`), '5');
const request = `select public.inventory_request_restock('${location}','trash',5,15,'Concurrent shortage','high');`;
const requests = await Promise.all([run(request), run(request)]);
assert.equal(requests.filter(r => r.ok).length, 1, JSON.stringify(requests));
assert.match(requests.find(r => !r.ok).stderr, /duplicate key/);
console.log('Concurrent withdrawals, negative prevention, identical retries and duplicate requests passed');
